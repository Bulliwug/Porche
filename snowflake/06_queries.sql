USE SCHEMA CAR_PRICING.PORSCHE;

-- Modello: prezzo base e numero di optional per esecuzione
SELECT SNAPSHOT_TS, LOCALE, MODEL_CODE, MODEL_NAME, BASE_PRICE, CURRENCY, N_OPTIONS
FROM PORSCHE_MODELS ORDER BY SNAPSHOT_TS DESC;

-- Optional dell'ultimo listino, dal più caro
SELECT SECTION, CATEGORY, OPTION_CODE, OPTION_NAME, PRICE, CURRENCY, IS_STANDARD
FROM V_OPTIONS_LATEST
WHERE MODEL_CODE = '95BBW1' AND LOCALE = 'en-US'
ORDER BY PRICE DESC NULLS LAST;

-- Riepilogo per sezione
SELECT SECTION, COUNT(*) AS N_OPTIONS,
       COUNT_IF(PRICE > 0) AS A_PAGAMENTO, COUNT_IF(IS_STANDARD) AS DI_SERIE,
       MAX(PRICE) AS PREZZO_MAX
FROM V_OPTIONS_LATEST
WHERE MODEL_CODE = '95BBW1' AND LOCALE = 'en-US'
GROUP BY SECTION ORDER BY N_OPTIONS DESC;

-- Variazioni di prezzo rispetto all'esecuzione precedente
SELECT * FROM V_PRICE_CHANGES ORDER BY SNAPSHOT_TS DESC, ABS(DELTA) DESC;

-- ===================== COMPASS POC =====================
-- Prezzo Visual (MSRP base) e destination charge
SELECT MODEL_NAME, MODEL_CODE, BASE_PRICE AS VISUAL_PRICE, DESTINATION_CHARGE,
       BASE_PRICE + DESTINATION_CHARGE AS MSRP_PLUS_DESTINATION, CURRENCY, PRICE_LIST_DATE, SNAPSHOT_TS
FROM PORSCHE_MODELS WHERE MODEL_CODE = '95BBW1' AND LOCALE = 'en-US'
QUALIFY SNAPSHOT_TS = MAX(SNAPSHOT_TS) OVER ();

-- Dotazioni di serie (terminologia Porsche) per area veicolo
SELECT VEHICLE_AREA, CATEGORY, OPTION_CODE, OPTION_NAME, DESCRIPTION
FROM V_COMPASS_STANDARD WHERE MODEL_CODE = '95BBW1' AND LOCALE = 'en-US'
ORDER BY VEHICLE_AREA, CATEGORY;

-- Optional singoli in perimetro POC
SELECT VEHICLE_AREA, OPTION_CODE, OPTION_NAME, PRICE, CURRENCY, IN_SCOPE, SCOPE_REASON
FROM V_COMPASS_OPTIONS_IN_SCOPE WHERE MODEL_CODE = '95BBW1' AND LOCALE = 'en-US'
ORDER BY IN_SCOPE, PRICE DESC;

-- Controllo classificazione: atteso (06/11/2026) 66 di serie, 116 singoli, 7 pacchetti, 34 colori/materiali
SELECT ITEM_TYPE, IN_SCOPE, COUNT(*) AS N
FROM V_OPTIONS_LATEST WHERE MODEL_CODE = '95BBW1' AND LOCALE = 'en-US'
GROUP BY ITEM_TYPE, IN_SCOPE ORDER BY N DESC;
